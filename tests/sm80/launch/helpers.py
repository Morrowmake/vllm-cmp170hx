def promote(world: World, layouts: list[str], *, generation: str | None = None,
            docs: dict | None = None, gate: str = "gate-synth-1") -> dict:
    """Write validated/<layout>.json files and receipt.json from resolved
    launches. ``generation`` set: publish as validated.d/<gen>/ behind the
    validated symlink; otherwise into a plain validated/ directory."""
    from canon import sha256_bytes
    docs = docs or {L: world.resolve(layout=L) for L in layouts}
    any_doc = next(iter(docs.values()))
    et = any_doc["engine_target"]
    pins = {}
    with open(os.path.join(world.settings, "pins.env")) as f:
        for line in f:
            if "=" in line and not line.startswith("#"):
                k, v = line.strip().split("=", 1)
                if k != "ENGINE_IMAGE":
                    pins[k] = v
    files: dict[str, bytes] = {}
    entries = {}
    for L, d in docs.items():
        vf = {
            "schema": "validated-launch/1", "model": d["model"], "layout": L,
            "argv_functional": d["argv_functional"], "env_functional": d["env_functional"],
            "functional_sha256": d["functional_sha256"], "engine_commit": et["commit"],
            "requires": d["requires"],
            "checkpoints": {n: c["manifest_sha256"] for n, c in d["checkpoint"].items()},
            "gate_record": gate,
        }
        raw = json.dumps(vf, indent=1, sort_keys=True).encode() + b"\n"
        files[f"{L}.json"] = raw
        entries[L] = {"validated_sha256": sha256_bytes(raw),
                      "functional_sha256": d["functional_sha256"], "gate_record": gate,
                      "verdict_revision": "rev-1", "gate_revision": "grev-1",
                      "requires": d["requires"]}
    engine = {"commit": et["commit"], "role": "validated",
              "native_manifest_sha256": et["build_owned"]["native_manifest_sha256"],
              "build_owned_sha256": et["build_owned"]["build_owned_sha256"]}
    if et.get("plugin") is not None:
        engine.update(plugin_commit=et["plugin"]["commit"], native_build=pins["NATIVE_BUILD"],
                      plugin_dist_sha256=et["plugin"]["plugin_dist_sha256"],
                      natives=et["plugin"]["natives"])
    receipt = {
        "schema": "validation-receipt/1", "model": any_doc["model"], "layouts": entries,
        "pins": pins,
        "engines": [engine],
        "checkpoints": {n: {"repo": c["repo"], "revision": c["revision"],
                            "manifest_sha256": c["manifest_sha256"]}
                        for n, c in any_doc["checkpoint"].items()},
        "promoted_at": "2026-01-01T00:00:00Z", "user_yes": "test", "promoter_commit": "0" * 40,
    }
    files["receipt.json"] = json.dumps(receipt, indent=1, sort_keys=True).encode() + b"\n"
    publish(world.settings, files, generation)
    return receipt


def publish(settings: str, files: dict[str, bytes], generation: str | None,
            pause_before_rename=None) -> None:
    pointer = os.path.join(settings, "validated")
    if generation is None:
        if os.path.islink(pointer):
            os.unlink(pointer)
        shutil.rmtree(pointer, ignore_errors=True)
        os.makedirs(pointer)
        target = pointer
    else:
        target = os.path.join(settings, "validated.d", generation)
        os.makedirs(target)
    for name, raw in files.items():
        with open(os.path.join(target, name), "wb") as f:
            f.write(raw)
    if generation is not None:
        tmp = os.path.join(settings, "validated.new")
        os.symlink(os.path.join("validated.d", generation), tmp)
        if pause_before_rename is not None:
            pause_before_rename()
        if os.path.isdir(pointer) and not os.path.islink(pointer):
            shutil.rmtree(pointer)
        os.replace(tmp, pointer)
