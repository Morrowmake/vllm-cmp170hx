def git(tree: str, *args: str) -> str:
    return subprocess.run(["git", "-C", tree, *args], check=True, capture_output=True,
                          text=True, env=GIT_ENV).stdout


def write(path: str, text: str) -> str:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return path


def envs_py(names: list[str], defaults: dict[str, str] | None = None) -> str:
    defaults = defaults or {}
    rows = "\n".join(f'    "{n}": lambda: os.getenv("{n}", "{defaults.get(n, "")}"),' for n in names)
    return f"import os\n\nenvironment_variables: dict = {{\n{rows}\n}}\n"


def sm80_envs_py(fork: dict[str, str], retired: dict[str, str]) -> str:
    rows = "\n".join(f'    "{n}": lambda: os.getenv("{n}", "{d}"),' for n, d in fork.items())
    rrows = "\n".join(f'    "{n}": ("{t}"),' for n, t in retired.items())
    return ("import os\n\nFORK_ENV_VARS: dict = {\n" + rows + "\n}\n\n"
            "RETIRED_ENV_VARS: dict[str, str] = {\n" + rrows + "\n}\n")


