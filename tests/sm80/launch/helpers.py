class World:
    """One tmp directory with a built tree, a venv, a checkpoint and settings."""

    def __init__(self, tmp, *, build: bool = True, **tree_kw) -> None:
        self.tmp = str(tmp)
        self.tree = make_tree(os.path.join(self.tmp, "tree"), **tree_kw)
        if build:
            add_build(self.tree)
        self.venv = make_venv(os.path.join(self.tmp, "venv"))
        self.models = os.path.join(self.tmp, "models")
        self.cp = make_checkpoint(os.path.join(self.models, "synth-dense-1b"))
        self.settings = make_settings(os.path.join(self.tmp, "settings"), commit=head(self.tree),
                                      checkpoint_dir=self.cp)
        self.stamps = os.path.join(self.tmp, "stamps")
        self.home = os.path.join(self.tmp, "home")
        os.makedirs(self.home, exist_ok=True)

    def base_args(self, *extra: str, layout: str | None = "tp2") -> list[str]:
        args = ["--runtime", "native", "--tree", self.tree, "--venv", self.venv,
                "--settings", self.settings, "--models-dir", self.models,
                "--stamp-dir", self.stamps]
        if layout:
            args += ["--layout", layout]
        return args + list(extra)

    def env(self, **extra: str) -> dict[str, str]:
        e = {"HOME": self.home, "LANG": "C.UTF-8", "TERM": "xterm"}
        e.update(extra)
        return e

    def resolve(self, *extra: str, layout: str | None = "tp2", environ: dict | None = None,
                expect_code: int = 0) -> dict:
        import main
        out, err = io.StringIO(), io.StringIO()
        with redirect_stdout(out), redirect_stderr(err):
            code = main.main(self.base_args("--print-config", "--json", *extra, layout=layout),
                             environ if environ is not None else self.env())
        assert code == expect_code, (code, err.getvalue(), out.getvalue()[:2000])
        return json.loads(out.getvalue()) if out.getvalue() else {"stderr": err.getvalue()}

    def refused(self, *extra: str, layout: str | None = "tp2", environ: dict | None = None) -> str:
        doc = self.resolve(*extra, layout=layout, environ=environ, expect_code=3)
        assert doc.get("schema") == "launch-refusal/1", doc
        return " | ".join(doc["reasons"])

    def verify(self) -> int:
        import checkpoint as ck
        out = io.StringIO()
        with redirect_stdout(out):
            return ck.main(["verify", "--settings", self.settings, "--models-dir", self.models,
                            "--stamp-dir", self.stamps])

    def run(self, *extra: str, layout: str | None = "tp2", environ: dict | None = None,
            python_flags: tuple[str, ...] = ("-I",)) -> subprocess.CompletedProcess:
        """Run main.py as a real process (exec path)."""
        return subprocess.run(
            [sys.executable, *python_flags, os.path.join(LAUNCH, "main.py"),
             *self.base_args(*extra, layout=layout)],
            env=environ if environ is not None else self.env(), capture_output=True, text=True)


