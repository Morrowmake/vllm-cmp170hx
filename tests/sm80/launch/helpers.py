def serve_py(parser_file: str = OLD_PARSER) -> str:
    module = parser_file.removesuffix(".py").replace("/", ".")
    return (f"from {module} import (\n    make_arg_parser,\n)\n"
            "from vllm.utils.argparse_utils import FlexibleArgumentParser\n\n\n"
            "def subparser_init(serve_parser):\n    return make_arg_parser(serve_parser)\n")


def make_tree(root: str, *, sm80: bool = True, fork: dict | None = None,
              retired: dict | None = None, upstream: list[str] | None = None,
              extra_files: dict[str, str] | None = None) -> str:
    os.makedirs(root, exist_ok=True)
    write(os.path.join(root, "vllm", "envs.py"), envs_py(upstream or UPSTREAM_VARS))
    write(os.path.join(root, "vllm", "__init__.py"), "")
    if sm80:
        write(os.path.join(root, "vllm_sm80", "envs.py"),
              sm80_envs_py(fork if fork is not None else FORK_VARS,
                           retired if retired is not None else RETIRED))
    write(os.path.join(root, "csrc", "kernel.cu"), "// kernel\n")
    write(os.path.join(root, "vllm", "engine", "arg_utils.py"), ARG_UTILS)
    write(os.path.join(root, SERVE), serve_py())
    write(os.path.join(root, OLD_PARSER), PARSER)
    write(os.path.join(root, ARGPARSE), PLAIN_ARGPARSE)
    write(os.path.join(root, ".gitignore"), "*.so\nbuild/\n")
    for rel, text in (extra_files or {}).items():
        write(os.path.join(root, rel), text)
    git(root, "init", "-q", "-b", "main")
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "base")
    return root


def head(tree: str) -> str:
    return git(tree, "rev-parse", "HEAD").strip()


def add_build(tree: str, files: dict[str, str] | None = None, *, source: str = "built_in_place",
              natives: str = "natives-1", stamp: bool = True, record: bool = True,
              commit: str | None = None) -> dict:
    """Build artefacts plus their provenance: owned files, a native manifest
    and a retained build record (both outside the tree), the build-owned
    manifest and the build stamp."""
    from canon import sha256_file
    from treestate import MANIFEST, build_owned_sha256
    files = BUILD if files is None else files
    for rel, text in files.items():
        write(os.path.join(tree, rel), text)
    owned = {rel: sha256_file(os.path.join(tree, rel)) for rel in files}
    side = os.path.join(os.path.dirname(tree), "build-" + os.path.basename(tree))
    native = write(os.path.join(side, "native-manifest.json"),
                   json.dumps({"artefacts": {}, "natives": natives}))
    man = {"schema": "build-owned/1", "source": source, "commit": commit or head(tree),
           "files": owned, "native_manifest_sha256": sha256_file(native),
           "native_manifest_path": native, "build_owned_sha256": build_owned_sha256(owned)}
    if record and source == "built_in_place":
        rec = write(os.path.join(side, "build-record.json"),
                    json.dumps({"schema": "build-record/1", "files": owned}))
        man["build_record"] = {"path": rec, "sha256": sha256_file(rec)}
    if source == "adopted":
        man["adopted"] = {"artefact_commit_source": "HEAD", "natives_checked": {}}
    write(os.path.join(tree, MANIFEST), json.dumps(man))
    if stamp:
        write_stamp(tree, man)
    return man


def write_stamp(tree: str, man: dict) -> None:
    """The build stamp of a tree at its HEAD, naming its manifest's hashes."""
    from treestate import STAMP
    write(os.path.join(tree, STAMP), json.dumps(
        {"schema": "build-stamp/1", "commit": head(tree),
         "native_manifest_sha256": man["native_manifest_sha256"],
         "build_owned_sha256": man["build_owned_sha256"]}))


