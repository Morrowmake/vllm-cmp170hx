def make_venv(root: str) -> str:
    """A venv whose bin/vllm records its argv, environment and open file
    descriptors, then exits. It is a Python script, so it adds nothing to
    its own environment."""
    rec = os.path.join(root, "record")
    stub = write(os.path.join(root, "bin", "vllm"), STUB.format(python=sys.executable, rec=rec))
    os.chmod(stub, 0o755)
    return root


def read_record(venv: str) -> tuple[list[str], dict[str, str]]:
    rec = os.path.join(venv, "record")
    with open(rec + ".argv", "rb") as f:
        argv = [a.decode() for a in f.read().split(b"\0") if a]
    with open(rec + ".environ", "rb") as f:
        env = dict(e.decode().split("=", 1) for e in f.read().split(b"\0") if e)
    return argv, env


